import "dotenv/config";
import express from "express";
import { marcPaywall } from "marc-stellar-sdk";
import { context, propagation, SpanKind, SpanStatusCode, trace } from "@opentelemetry/api";
import { NodeTracerProvider } from "@opentelemetry/sdk-trace-node";
import { BatchSpanProcessor } from "@opentelemetry/sdk-trace-base";
import { OTLPTraceExporter } from "@opentelemetry/exporter-trace-otlp-http";
import { resourceFromAttributes } from "@opentelemetry/resources";
import { ATTR_SERVICE_NAME } from "@opentelemetry/semantic-conventions";

const serviceName = process.env.OTEL_SERVICE_NAME ?? "seller-mock";

const provider = new NodeTracerProvider({
  resource: resourceFromAttributes({
    [ATTR_SERVICE_NAME]: serviceName,
  }),
  spanProcessors: [
    new BatchSpanProcessor(
      new OTLPTraceExporter({
        url:
          process.env.OTEL_EXPORTER_OTLP_TRACES_ENDPOINT ??
          process.env.OTEL_EXPORTER_OTLP_ENDPOINT ??
          "http://localhost:4318/v1/traces",
      }),
    ),
  ],
});

provider.register();

const tracer = trace.getTracer(serviceName);

const app = express();
const port = Number(process.env.PORT ?? 4510);
const payTo = process.env.PAY_TO ?? "GAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA";

app.use(express.json());

app.use((req, res, next) => {
  const parentContext = propagation.extract(context.active(), req.headers);
  const span = tracer.startSpan(
    `${req.method} ${req.path}`,
    {
      kind: SpanKind.SERVER,
      attributes: {
        "http.request.method": req.method,
        "url.path": req.path,
        "url.scheme": req.protocol,
        "server.address": req.hostname,
        "http.route": req.path,
      },
    },
    parentContext,
  );

  res.on("finish", () => {
    span.setAttribute("http.response.status_code", res.statusCode);
    if (res.statusCode >= 500) {
      span.setStatus({ code: SpanStatusCode.ERROR });
    }
    span.end();
  });

  res.on("close", () => {
    if (!res.writableEnded) {
      span.setStatus({ code: SpanStatusCode.ERROR, message: "connection closed" });
      span.end();
    }
  });

  context.with(trace.setSpan(parentContext, span), () => {
    next();
  });
});

const mockPaywall = marcPaywall({
  payTo,
  price: "$0.01",
  network: "stellar:testnet",
  description: "Access the local mock seller agent",
  mimeType: "application/json",
  facilitatorUrl:
    process.env.X402_FACILITATOR_URL ?? "https://channels.openzeppelin.com/x402/testnet",
  facilitatorApiKey: process.env.X402_API_KEY,
});

app.get("/health", (_req, res) => {
  res.json({
    ok: true,
    service: "seller-mock",
    status: "healthy",
    port,
    payTo,
  });
});

app.get("/api/mock", mockPaywall, (_req, res) => {
  res.json({
    success: true,
    agent: "seller-mock",
    message: "Static mock seller response for local buyer integration tests.",
    deliverable: {
      format: "json",
      content: {
        summary: "This response was generated by the mock seller agent.",
        status: "ok",
      },
    },
    payment: {
      required: true,
      amount: "$0.01",
      asset: "USDC",
    },
  });
});

app.get("/", (_req, res) => {
  res.json({
    service: "seller-mock",
    endpoints: [
      "GET /health",
      "GET /api/mock",
    ],
  });
});

const server = app.listen(port, () => {
  console.log(`[seller-mock] listening on http://localhost:${port}`);
  console.log(`[seller-mock] protected endpoint: http://localhost:${port}/api/mock`);
});

const shutdown = () => {
  server.close(() => {
    provider
      .shutdown()
      .catch((err) => console.error("[seller-mock] failed to shutdown tracing", err))
      .finally(() => process.exit(0));
  });
};

process.on("SIGTERM", shutdown);
process.on("SIGINT", shutdown);
